"""Generate src/OepEspPsram.h from ESP-IDF-SoC-Check (https://github.com/tanakamasayuki/ESP-IDF-SoC-Check).

What ESP-IDF does not declare: which eFuse field tells a chip's in-package PSRAM (chip_efuse_fields.csv, key
psram_cap), the capacity each of its values means (chip_features.csv, "Embedded PSRAM <n>MB" / psram_cap=<v>) and that
capacity's interface (psram_interfaces.csv: Quad, Octal, Unknown). The header maps each value to none / quad / octal /
unknown for platformUnusablePins() (OepPlatform.h).

    tools/gen_esp_psram.py PATH_TO_ESP-IDF-SoC-Check        (or ESP_IDF_SOC_CHECK=PATH tools/gen_esp_psram.py)
"""
import argparse
import csv
import os
import re
import subprocess
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "OepEspPsram.h"


def rows(path: Path) -> list[dict]:
    with path.open(newline="") as f:
        return list(csv.DictReader((line for line in f if not line.startswith("#")), delimiter="\t"))


def kind(interface: str | None) -> str:
    if interface is None:
        return "kUnknown"
    word = interface.split("/")[0].strip().lower()
    return {"quad": "kQuad", "octal": "kOctal"}.get(word, "kUnknown")


def generate(src: Path) -> str:
    fields: dict[str, set[str]] = {}
    for r in rows(src / "chip_efuse_fields.csv"):
        if r["key"] == "psram_cap" and r["idf_field"]:
            fields.setdefault(r["chip"], set()).add(r["idf_field"])
    caps: dict[str, dict[int, int]] = {}
    for r in rows(src / "chip_features.csv"):
        m = re.fullmatch(r"Embedded PSRAM (\d+)MB", r["feature"].strip())
        c = re.fullmatch(r"psram_cap=(\d+)", r["condition"].strip())
        if m and c:
            caps.setdefault(r["chip"], {})[int(c.group(1))] = int(m.group(1))
    interfaces = {(r["chip"], int(r["capacity_mb"])): r["interface"] for r in rows(src / "psram_interfaces.csv")}
    try:
        commit = subprocess.run(["git", "-C", str(src), "rev-parse", "--short", "HEAD"], capture_output=True,
                                text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"

    out = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Open Embedded Probe",
        f"// Generated by tools/gen_esp_psram.py from ESP-IDF-SoC-Check {commit} - do not edit.",
        "//",
        "// An ESP32's in-package PSRAM, from its eFuse: OEP_ESP_PSRAM_CAP_FIELD names the field (esp_efuse_table.h) and",
        "// esp_psram::kByCap[value] the kind (kNone: no PSRAM in the package; kUnknown: a value whose interface no",
        "// datasheet gives). Chips not listed have no such field.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace oep {",
        "namespace esp_psram {",
        "",
        "enum Kind : uint8_t { kNone = 0, kQuad = 1, kOctal = 2, kUnknown = 3 };",
        "",
    ]
    first = True
    for chip in sorted(fields):
        names = fields[chip]
        if len(names) != 1 or chip not in caps:
            continue
        table = caps[chip]
        size = max(table) + 1
        entries, notes = [], []
        for v in range(size):
            if v == 0:
                entries.append("kNone"); notes.append("0 none")
            elif v in table:
                k = kind(interfaces.get((chip, table[v])))
                entries.append(k); notes.append(f"{v} {table[v]} MB")
            else:
                entries.append("kUnknown"); notes.append(f"{v} ?")
        out.append(f"#{'if' if first else 'elif'} defined(CONFIG_IDF_TARGET_{chip.upper()})")
        out.append(f"#define OEP_ESP_PSRAM_CAP_FIELD ESP_EFUSE_{next(iter(names))}")
        out.append(f"constexpr Kind kByCap[] = {{{', '.join(entries)}}};   // {', '.join(notes)}")
        first = False
    if not first:
        out.append("#endif")
    out += ["", "}  // namespace esp_psram", "}  // namespace oep", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", default=os.environ.get("ESP_IDF_SOC_CHECK"),
                    help="the ESP-IDF-SoC-Check checkout (default: $ESP_IDF_SOC_CHECK)")
    ap.add_argument("--check", action="store_true", help="fail if src/OepEspPsram.h differs instead of writing it")
    a = ap.parse_args()
    if not a.source:
        ap.error("give the ESP-IDF-SoC-Check checkout (argument or ESP_IDF_SOC_CHECK)")
    text = generate(Path(a.source))
    if a.check:
        raise SystemExit(0 if OUT.exists() and OUT.read_text() == text else f"{OUT} is out of date")
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
